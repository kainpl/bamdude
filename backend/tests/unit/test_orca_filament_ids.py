"""OrcaSlicer's own "OF…" filament ids never reach a printer (upstream dab7c60a9·7, owner decision Р16).

OrcaSlicer 2.5 content-addresses every BBL system filament and translates to
Bambu's ids only at the printer boundary. A printer resolves Bambu's ids only,
so an Orca Cloud profile carrying ``filament_id: "OF…"`` used to mint a family
of that id and send it as ``tray_info_idx``. The table is GENERATED by
``scripts/distill_filament_catalog.py`` from Orca's own
``resources/printers/bambu_filament_ids.json`` and read in one place,
``filament_catalog.bambu_filament_id``.
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import pytest

from backend.app.services.filament_preset_sync import _orca_family_id
from backend.app.utils import filament_catalog as catalog

_REPO = Path(__file__).resolve().parents[3]
_TABLE = _REPO / "backend" / "app" / "data" / "filament_catalog" / "orca_filament_ids.json"


def _distiller():
    spec = importlib.util.spec_from_file_location(
        "distill_filament_catalog", _REPO / "scripts" / "distill_filament_catalog.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class TestTheGeneratedTable:
    def test_every_orca_id_names_a_family_the_catalog_knows(self):
        ids = json.loads(_TABLE.read_text(encoding="utf-8"))["ids"]
        assert ids, "the table is generated by the distiller and must not be empty"
        assert all(orca_id.startswith("OF") for orca_id in ids)
        assert [bambu_id for bambu_id in ids.values() if catalog.get_family(bambu_id) is None] == []

    def test_the_shipped_catalog_holds_no_orca_id(self):
        """What a re-distil from Orca 2.5 must keep true: families are Bambu ids."""
        for ecosystem in ("bambu", "orca"):
            assert [fid for fid in catalog._load(ecosystem).families if fid.startswith("OF")] == []


class TestTheOneTranslator:
    def test_a_known_orca_id_is_its_bambu_id(self):
        assert catalog.bambu_filament_id("OF0UJcb6") == "GFG60"  # PolyLite PETG
        assert catalog.bambu_filament_id("OF1UNk9P") == "GFP97"  # Generic PP

    def test_an_unknown_orca_id_is_no_id(self):
        assert catalog.bambu_filament_id("OFzzzzzz") is None

    @pytest.mark.parametrize("own", ["GFL99", "GFSNL03", "P122e532", "PFUS9ac902733670a9"])
    def test_every_other_id_is_itself(self, own):
        assert catalog.bambu_filament_id(own) == own

    @pytest.mark.parametrize("empty", [None, "", "  "])
    def test_nothing_is_nothing(self, empty):
        assert catalog.bambu_filament_id(empty) is None


class TestOrcaProfileFamily:
    def test_a_profile_with_a_known_orca_id_gets_the_bambu_family(self):
        assert _orca_family_id({"filament_id": "OF0UJcb6"}) == "GFG60"

    def test_an_unknown_orca_id_falls_through_to_the_parent(self):
        content = {"filament_id": "OFzzzzzz", "inherits": "Generic PLA @BBL X1C"}
        assert _orca_family_id(content) == "GFL99"

    def test_an_unknown_orca_id_with_no_parent_is_no_family(self):
        assert _orca_family_id({"filament_id": "OFzzzzzz"}) is None

    def test_a_profiles_own_id_still_wins(self):
        """#3216's own example — what Orca's Device tab writes."""
        assert _orca_family_id({"filament_id": "Pfc74047", "inherits": "Generic PLA @BBL X1C"}) == "Pfc74047"


class TestInheritsChain:
    """Upstream 02e39b18b·2: a profile that stores only a diff takes its parent's id."""

    def test_a_child_of_the_users_own_profile(self):
        siblings = {"My PETG": {"filament_id": "Pabc1234", "inherits": "Generic PETG @BBL X1C"}}
        assert _orca_family_id({"inherits": "My PETG"}, siblings) == "Pabc1234"

    def test_a_grandchild(self):
        siblings = {
            "My PETG": {"filament_id": "Pabc1234"},
            "My PETG slow": {"inherits": "My PETG"},
        }
        assert _orca_family_id({"inherits": "My PETG slow"}, siblings) == "Pabc1234"

    def test_a_cycle_ends_without_a_family(self):
        siblings = {"A": {"inherits": "B"}, "B": {"inherits": "A"}}
        assert _orca_family_id({"inherits": "A"}, siblings) is None

    def test_a_chain_longer_than_the_bound_ends_without_a_family(self):
        siblings = {f"P{i}": {"inherits": f"P{i + 1}"} for i in range(20)}
        siblings["P20"] = {"filament_id": "Pabc1234"}
        assert _orca_family_id({"inherits": "P0"}, siblings) is None

    def test_a_system_parent_of_a_printer_the_catalog_does_not_carry(self):
        """The name before "@" still says which filament it is."""
        assert _orca_family_id({"inherits": "Generic PETG @BBL Some Future Printer"}) == "GFG99"

    def test_a_parent_nobody_knows_is_no_family(self):
        assert _orca_family_id({"inherits": "Nobody's Filament @Nowhere"}) is None


class TestDistiller:
    def _checkout(self, root: Path, *, with_table: bool) -> Path:
        filament = root / "resources" / "profiles" / "BBL" / "filament"
        filament.mkdir(parents=True)

        def write(name: str, data: dict) -> None:
            (filament / f"{name}.json").write_text(json.dumps({"name": name, **data}), encoding="utf-8")

        write(
            "Generic PLA @base", {"filament_id": "OFaaaaaa", "filament_type": ["PLA"], "filament_vendor": ["Generic"]}
        )
        write(
            "Generic PLA @BBL X1C",
            {"inherits": "Generic PLA @base", "instantiation": "true", "setting_id": "GFSL99_00"},
        )
        write("Mystery @base", {"filament_id": "OFbbbbbb", "filament_type": ["PLA"]})
        write("Mystery @BBL X1C", {"inherits": "Mystery @base", "instantiation": "true", "setting_id": "XX_00"})
        if with_table:
            printers = root / "resources" / "printers"
            printers.mkdir(parents=True)
            (printers / "bambu_filament_ids.json").write_text(
                json.dumps({"filaments": {"OFaaaaaa": {"bambu_id": "GFL99", "name": "Generic PLA"}}}), encoding="utf-8"
            )
        return root

    def test_the_catalog_it_writes_holds_bambu_ids_only(self, tmp_path):
        distiller = _distiller()
        catalog_out, errors = distiller.distill(self._checkout(tmp_path, with_table=True), "test")

        assert [f["filament_id"] for f in catalog_out["families"]] == ["GFL99"]
        assert [(p["name"], p["filament_id"]) for p in catalog_out["presets"]] == [("Generic PLA @BBL X1C", "GFL99")]
        # The Orca id its table does not know is reported, never a family.
        assert any("Mystery @base" in line for line in errors)

    def test_the_id_table_is_the_checkouts_own(self, tmp_path):
        distiller = _distiller()
        table = distiller.distill_ids(self._checkout(tmp_path, with_table=True), "test")
        assert table["ids"] == {"OFaaaaaa": "GFL99"}

    def test_a_checkout_without_the_table_distils_as_before(self, tmp_path):
        """BambuStudio and OrcaSlicer < 2.5: the ids already are Bambu's."""
        distiller = _distiller()
        checkout = self._checkout(tmp_path, with_table=False)
        catalog_out, _errors = distiller.distill(checkout, "test")
        assert distiller.distill_ids(checkout, "test") is None
        assert sorted(f["filament_id"] for f in catalog_out["families"]) == ["OFaaaaaa", "OFbbbbbb"]
